// Перевод строки интерфейса: нет в словаре — остаётся русская
function t(s) { return (I18N[LANG] && I18N[LANG][s]) || s; }

// Локаль для чисел: 22 241 / 22,241 / 22 241
function numLocale() { return NUM_LOCALES[LANG] || "en-US"; }

// Поле данных на текущем языке. "name_ru" → name_<lang>; остальные (fun_fact, hint, how, title, question,
// unit, compare_phrase, compare_less) → <field>_<lang>. Нет поля — пробуем словарь, потом русское значение.
function L(obj, field) {
  if (!obj) return undefined;
  if (LANG === "ru") return obj[field];
  const key = field === "name_ru" ? "name_" + LANG : field + "_" + LANG;
  return obj[key] || t(obj[field]);
}

// Статический текст из index.html: data-i18n (textContent), data-i18n-ph (placeholder),
// data-i18n-title (title), data-i18n-val (value — только если в поле ещё стоит значение по умолчанию)
function applyStaticText() {
  document.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll("[data-i18n-ph]").forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
  document.querySelectorAll("[data-i18n-title]").forEach((el) => { el.title = t(el.dataset.i18nTitle); });
  document.querySelectorAll("[data-i18n-val]").forEach((el) => {
    const key = el.dataset.i18nVal;
    const defaults = [key, ...Object.keys(I18N).map((l) => I18N[l][key])];
    if (defaults.includes(el.value)) el.value = t(key);
  });
  document.querySelectorAll("#lang-switch [data-lang]").forEach((b) => b.classList.toggle("active", b.dataset.lang === LANG));
}

function setLang(l) {
  if (!LANGS[l]) return;
  LANG = l;
  localStorage.setItem("atl_lang", l);
  document.documentElement.lang = l;
  applyStaticText();
  renderHome();   // game.js
}

document.documentElement.lang = LANG;
document.querySelectorAll("#lang-switch [data-lang]").forEach((b) => { b.onclick = () => setLang(b.dataset.lang); });
applyStaticText();

